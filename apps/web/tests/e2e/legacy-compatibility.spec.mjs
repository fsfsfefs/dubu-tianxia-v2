import {test,expect} from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
test('v1 backup upgrades before restore and old summaries use new PDF navigation',async({page})=>{
 const docs=(await (await page.request.get('/api/documents')).json()).documents;
 const book=docs.find(d=>d.title==='E2E Native');
 const temp=fs.mkdtempSync(path.resolve('../../.tmp/legacy-browser-'));
 const current=path.join(temp,'current.zip'),legacy=path.join(temp,'legacy.zip');
 const downloaded=await page.request.get('/api/backup/full');expect(downloaded.ok()).toBe(true);
 fs.writeFileSync(current,await downloaded.body());
 const local=path.resolve('../api/.venv/Scripts/python.exe');
 const created=spawnSync(fs.existsSync(local)?local:'python',['tests/e2e/make-legacy-backup.py',current,legacy,book.id],{encoding:'utf8'});
 expect(created.status,created.stderr).toBe(0);
 const imported=await page.request.post('/api/backup/restore',{multipart:{file:{name:'legacy.zip',mimeType:'application/zip',buffer:fs.readFileSync(legacy)}}});
 expect(imported.ok(),await imported.text()).toBe(true);
 expect((await imported.json()).compatibility.chapters_upgraded).toBeGreaterThanOrEqual(1);
 await page.goto('/');
 await page.locator('.library-book').filter({hasText:'E2E Native'}).getByRole('button',{name:/打开教材/}).click();
 await page.locator('.chapter-entry').filter({hasText:'兼容第一章'}).click();
 await page.getByRole('button',{name:'查看原PDF第2页：PDF2',exact:true}).click();
 await expect(page.locator('.page-controls input')).toHaveValue('2');
 await page.getByRole('button',{name:'章节总结',exact:true}).click();
 const panel=page.getByRole('complementary',{name:'PDF章节总结'});
 await expect(panel).toBeVisible();
 const select=panel.getByLabel('查看章节总结');
 const history=await select.locator('option').filter({hasText:'历史总结'}).getAttribute('value');
 await select.selectOption(history);
 await expect(panel.getByRole('status')).toContainText('尚未可靠匹配');
 await expect(panel.getByRole('button',{name:'查看原PDF第1页：PDF1'})).toBeVisible();
});
